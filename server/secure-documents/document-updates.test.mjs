import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {randomBytes} from 'node:crypto';
import {openDevTenantStore} from './sqlite-tenant-store.mjs';

test('role-scoped durable changes without document contents',t=>{
 const dir=mkdtempSync(join(tmpdir(),'seyveo-events-'));
 t.after(()=>rmSync(dir,{recursive:true,force:true}));
 const settings={filePath:join(dir,'events.sqlite'),masterKey:randomBytes(32)};
 let store=openDevTenantStore(settings);
 let owner={userId:'owner'},elena={userId:'elena'},anna={userId:'anna'},other={userId:'other'};
 store.bootstrapOrganization({organizationId:'company',ownerUserId:'owner'});
 store.bootstrapOrganization({organizationId:'otherco',ownerUserId:'other'});
 store.addMember({actor:owner,organizationId:'company',userId:'elena',role:'employee'});
 store.addMember({actor:owner,organizationId:'company',userId:'anna',role:'employee'});
 const d=store.createDocument({actor:owner,organizationId:'company',recipientUserId:'elena',type:'acknowledgement',title:'Secret training title',body:'Private training body'});
 const fresh=store.getUpdates({actor:elena,organizationId:'company',after:0});
 assert.equal(fresh.events.length,1);assert.equal(fresh.events[0].kind,'assigned');
 assert.equal(JSON.stringify(fresh).includes('Secret training title'),false);
 assert.equal(JSON.stringify(fresh).includes('Private training body'),false);
 assert.equal(store.getUpdates({actor:anna,organizationId:'company'}).events.length,0);
 assert.equal(store.getUpdates({actor:other,organizationId:'otherco'}).events.length,0);
 assert.equal(store.getUpdates({actor:owner,organizationId:'company'}).events.length,0);
 assert.equal(store.getUpdates({actor:elena,organizationId:'company',after:fresh.nextCursor}).events.length,0);
 const acknowledged=store.transition({actor:elena,organizationId:'company',documentId:d.id,action:'acknowledge'});
 assert.equal(acknowledged.status,'acknowledged');
 const ownerEvents=store.getUpdates({actor:owner,organizationId:'company'});
 assert.equal(ownerEvents.events.length,1);assert.equal(ownerEvents.events[0].kind,'status_changed');
 const previous=ownerEvents.nextCursor;
 assert.equal(store.getUpdates({actor:owner,organizationId:'company',after:previous}).events.length,0);
 store.close();
 store=openDevTenantStore(settings);
 assert.equal(store.getUpdates({actor:owner,organizationId:'company'}).events.length,1);
 store.revokeMember({actor:owner,organizationId:'company',userId:'elena'});
 assert.throws(()=>store.getUpdates({actor:elena,organizationId:'company'}));
 assert.throws(()=>store.getUpdates({actor:owner,organizationId:'company',after:-1}));
 assert.throws(()=>store.getUpdates({actor:owner,organizationId:'company',after:0,limit:51}));
 store.close();
});
