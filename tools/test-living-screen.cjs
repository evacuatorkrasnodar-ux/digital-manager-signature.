'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const base=path.resolve(__dirname,'..');
const source=file=>fs.readFileSync(path.join(base,file),'utf8');
const {resolve,ruCount}=require('../assets/living-screen-core.js');
assert.equal(ruCount(1,'дело','дела','дел'),'1 дело');
assert.equal(ruCount(2,'дело','дела','дел'),'2 дела');
assert.equal(ruCount(12,'дело','дела','дел'),'12 дел');
assert.equal(ruCount(21,'дело','дела','дел'),'21 дело');
assert.equal(resolve({screen:'home'}).line,'');
assert.match(resolve({screen:'tasks',priority:true,count:2}).line,/ближайшее дело/i);
assert.match(resolve({screen:'tasks',priority:false,count:0}).line,/нет/);
assert.match(resolve({screen:'calendar',mode:'deadlines'}).line,/сроки/);
assert.match(resolve({screen:'calendar',mode:'day',selection:true}).line,/выбранной даты/);
assert.match(resolve({screen:'picture',count:3}).line,/3 показателя/);
assert.match(resolve({screen:'picture',count:0}).line,/появятся/);
assert.match(resolve({screen:'manage'}).line,/разрешено/);
assert.match(resolve({screen:'life'}).line,/вашим контролем/);
assert.match(resolve({screen:'music',playing:true}).line,/Музыка играет/);
const js=source('assets/living-space.js');
const css=source('assets/living-space.css');
const html=source('index.html');
const roadmap=source('assets/management.js');
assert.match(js,/function scheduleDirector\(\)/);
assert.match(js,/scheduleDirector\(\);\s*\n\}/);
assert.match(js,/if\(currentScreen==='home'\)/,'Original Home is explicitly exempt');
assert.match(js,/root\.dataset\.svLivingScene=scene\.context/);
assert.match(js,/window\.SEYVEO_LIVING_SCREEN=Object\.freeze/);
assert.match(js,/pendingTaskCount=Number\.isInteger/);
assert.match(js,/seyveo:calendar-changed/);
assert.match(js,/seyveo:tasks-changed/);
assert.doesNotMatch(js,/setInterval\(/,'No perpetual timers');
assert.doesNotMatch(js,/localStorage\.setItem/,'No duplicated private data');
assert.match(js,/dock\.dataset\.svLivingContext=scene\.context/,'Existing dock receives genuine context');
assert.doesNotMatch(css,/--sv-living-dock-glint|outline:\s*1px solid var\(--sv-living-dock-glint\)/,'Living Ink never draws a passive ring around Sayvi');
assert.match(html,/living-screen-core\.js\?v=\d+/);
assert.ok(html.indexOf('living-screen-core.js')<html.indexOf('assets/living-space.js'),'Core must load first');
assert.equal((html.match(/<footer class="dock"/g)||[]).length,1);
assert.equal((html.match(/id="orbCluster"/g)||[]).length,1);
assert.equal((roadmap.match(/\['living_screen_director'/g)||[]).length,1);
console.log('PASS Living Screen: rule-based scene director, original Home + dock, real signals.');
